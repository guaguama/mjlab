"""New OSL full-body robot constants.

A right transfemoral amputee: the left leg is intact, and the right leg below the
femur is an Open-Source Leg (OSL) prosthesis. Generated by musclemimic's
``scripts/generate_osl_fullbody_robot.py`` from the ``new_osl_fullbody``
musculoskeletal model, with the muscles replaced by joint actuators.

The vendored ``xmls/osl_fullbody_robot.xml`` is a **byte-identical** copy of
musclemimic's output. Every adaptation mjlab needs is applied programmatically in
:func:`get_spec`, so a re-import is a file copy and never a diff. Never hand-edit the
XML; regenerate it in musclemimic.

Of the 73 non-free joints, 29 are actuated (27 position servos + the 2 OSL torque
motors) and the remaining 44 are driven by ``mjEQ_JOINT`` equality constraints.

.. warning::
   ``XmlActuatorCfg`` inherits ``armature``, ``frictionloss`` and ``viscous_damping``
   from ``ActuatorCfg``, but ``xml_actuator.py`` never reads them -- only the builtin
   and PD actuators do. Setting them here is a silent no-op, and there is no
   ``effort_limit`` field either. The model's own ``<default>`` classes supply all of
   these. Any change to servo physics means regenerating the MJCF in musclemimic.
"""

